"""Reel pipeline: raw Slovene clips -> reviewed cuts -> 1080x1920 reel with burned-in captions.

  python reel.py ingest PROJECT clip1.mp4 [clip2.mp4 ...]
      copies clips to PROJECT/intake/, runs sl-stt (words with forced-aligned timings) and cutlist per clip,
      writes PROJECT/edl.json (defaults) and PROJECT/REVIEW.md (transcript, proposed cuts, low-confidence words).
  (the director reviews REVIEW.md, edits edl.json: cut decisions, clip order, text fixes, caption style)
  python reel.py render PROJECT [--draft]
      per clip: applies cuts -> PROJECT/work/<clip>/cut.mp4; joins clips; maps words onto the cut timeline,
      applies text fixes (re-aligned against the audio); renders captions over the video with HyperFrames
      -> PROJECT/out/reel.mp4 (1080x1920, 30 fps) + reel.srt + frames.png (contact sheet to check).

Tools: ~/claude-kit/tools/sl-stt (RSDO ASR + P&C), cut/cutlist.py, cut/render_cut.py, captions/render_captions.py.
Tested on FLEURS read speech only (2026-10-28). Stepan's own clip is the real test.
"""
import argparse, json, os, shutil, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
STT = os.path.join(os.path.dirname(HERE), "sl-stt")
STT_PY = os.path.join(STT, ".venv", "Scripts", "python.exe") if os.name == "nt" else os.path.join(STT, ".venv", "bin", "python")
sys.path.insert(0, os.path.join(HERE, "cut"))
from cutlist import detect, keep_segments  # noqa: E402


def run(cmd, **kw):
    print("  $", " ".join(str(c) for c in cmd)[:200], flush=True)
    subprocess.run([str(c) for c in cmd], check=True, **kw)


def stt(args):
    run([STT_PY, "-X", "utf8", os.path.join(STT, "sl_stt.py"), *args])


def ingest(a):
    P = os.path.abspath(a.project)
    for d in ("intake", "work", "out"):
        os.makedirs(os.path.join(P, d), exist_ok=True)
    clips = []
    for src in a.clips:
        name = os.path.splitext(os.path.basename(src))[0]
        dst = os.path.join(P, "intake", os.path.basename(src))
        if os.path.abspath(src) != dst:
            shutil.copy2(src, dst)
        w = os.path.join(P, "work", name)
        stt(["transcribe", dst, "-o", w])
        words = json.load(open(os.path.join(w, "words.json"), encoding="utf-8"))
        cuts = detect(words["words"], words["duration"])
        json.dump(dict(source=dst, duration=words["duration"], cuts=cuts), open(os.path.join(w, "cuts.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        clips.append(dict(name=name, src=os.path.relpath(dst, P), decisions={}, fixes={}))
    edl_path = os.path.join(P, "edl.json")
    if not os.path.exists(edl_path):
        json.dump(dict(clips=clips, overlays=[], captions=dict(style="klasika", accent=None, top=1180, max_lines=2),
                       export=dict(width=1080, height=1920, fps=30, out="out/reel.mp4", punch_in=True, punch_scale=1.15)),
                  open(edl_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    write_review(P, [c["name"] for c in clips])
    print(f"ingested {len(clips)} clip(s); review {os.path.join(P, 'REVIEW.md')}, then edit edl.json and run render")


def write_review(P, names):
    out = ["# Review sheet (generated by reel.py ingest)", "",
           "For each clip: check the transcript, decide every `propose` cut (edl.json clips[].decisions: {\"<cut id>\": \"cut\"|\"keep\"}),",
           "and list text fixes for names/numbers/terms (clips[].fixes: {\"wrong\": \"right\"}). Auto cuts apply unless set to \"keep\".", ""]
    for n in names:
        w = os.path.join(P, "work", n)
        words = json.load(open(os.path.join(w, "words.json"), encoding="utf-8"))
        cuts = json.load(open(os.path.join(w, "cuts.json"), encoding="utf-8"))["cuts"]
        out += [f"## {n} ({words['duration']:.1f} s)", "", "**Transcript** (time in s; ⚠ = low alignment confidence):", ""]
        line, t0 = [], None
        for x in words["words"]:
            if t0 is None: t0 = x["s"]
            line.append(x["w"] + (" ⚠" if x.get("conf", 1) < 0.3 else ""))
            if x["w"][-1:] in ".!?" or len(line) > 18:
                out.append(f"- `{t0:6.2f}` " + " ".join(line)); line, t0 = [], None
        if line: out.append(f"- `{t0:6.2f}` " + " ".join(line))
        out += ["", "**Cuts:**", "", "| id | level | from | to | reason |", "|---|---|---|---|---|"]
        out += [f"| {c['id']} | {c['level']} | {c['start']:.2f} | {c['end']:.2f} | {c['reason']} |" for c in cuts]
        out.append("")
    open(os.path.join(P, "REVIEW.md"), "w", encoding="utf-8").write("\n".join(out))


def apply_fixes(text_words, fixes):
    """word-level replacements {"wrong": "right"}; matching ignores case and trailing punctuation, which is kept"""
    low = {k.lower(): v for k, v in fixes.items()}
    out = []
    for w in text_words:
        core = w.rstrip(".,!?:;")
        out.append(low.get(core.lower(), core) + w[len(core):])
    return out


def render(a):
    P = os.path.abspath(a.project)
    edl = json.load(open(os.path.join(P, "edl.json"), encoding="utf-8"))
    ex = edl["export"]; W, H, FPS = ex["width"], ex["height"], ex["fps"]
    parts, all_words, offset = [], [], 0.0
    for c in edl["clips"]:
        w = os.path.join(P, "work", c["name"])
        cuts = json.load(open(os.path.join(w, "cuts.json"), encoding="utf-8"))
        for cut in cuts["cuts"]:  # director decisions override levels
            dec = c.get("decisions", {}).get(cut["id"])
            if dec: cut["level"] = "auto" if dec == "cut" else "keep"
        json.dump(cuts, open(os.path.join(w, "cuts.final.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        cut_mp4 = os.path.join(w, "cut.mp4")
        # normalise to WxH (cover crop) and FPS while cutting
        norm_mp4 = os.path.join(w, "norm.mp4")
        if not os.path.exists(norm_mp4) or os.path.getmtime(norm_mp4) < os.path.getmtime(os.path.join(P, c["src"])):
            run(["ffmpeg", "-y", "-v", "error", "-i", os.path.join(P, c["src"]), "-vf",
                 f"scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},fps={FPS},setsar=1",
                 "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "192k", norm_mp4])
        run([sys.executable, os.path.join(HERE, "cut", "render_cut.py"), norm_mp4, os.path.join(w, "cuts.final.json"), cut_mp4])
        # words on the cut timeline: re-align (fixed) text against the cut audio, so joins and fixes are exact
        cut_wav = os.path.join(w, "cut.wav")
        run(["ffmpeg", "-y", "-v", "error", "-i", cut_mp4, "-ar", "16000", "-ac", "1", cut_wav])
        keep = keep_segments(cuts["cuts"], cuts["duration"])
        src_words = json.load(open(os.path.join(w, "words.json"), encoding="utf-8"))["words"]
        kept = [x["w"] for x in src_words if any(s - 0.02 <= x["s"] and x["e"] <= e + 0.02 for s, e in keep)]
        text = apply_fixes(kept, c.get("fixes", {}))
        open(os.path.join(w, "cut_text.txt"), "w", encoding="utf-8").write(" ".join(text) + "\n")
        stt(["align", cut_wav, os.path.join(w, "cut_text.txt"), "-o", os.path.join(w, "cut_words.json")])
        cw = json.load(open(os.path.join(w, "cut_words.json"), encoding="utf-8"))
        all_words += [dict(w=x["w"], s=round(x["s"] + offset, 3), e=round(x["e"] + offset, 3)) for x in cw["words"]]
        offset += cw["duration"]; parts.append(cut_mp4)
    joined = os.path.join(P, "work", "joined.mp4")
    if len(parts) == 1:
        shutil.copy2(parts[0], joined)
    else:
        lst = os.path.join(P, "work", "join.txt")
        open(lst, "w").write("".join(f"file '{p}'\n" for p in parts))
        run(["ffmpeg", "-y", "-v", "error", "-f", "concat", "-safe", "0", "-i", lst, "-c", "copy", joined])
    if ex.get("punch_in", True):  # talking-head rule: no static shot (TikTok ads guidance, A, S2-32); zoom alternate sentences (ours)
        spans, start, n = [], None, 0
        for x in all_words:
            if start is None: start = x["s"]
            if x["w"][-1:] in ".!?":
                if n % 2 == 1: spans.append((start, x["e"]))
                start, n = None, n + 1
        if spans:
            z = ex.get("punch_scale", 1.15)
            cond = "+".join(f"between(t,{s:.2f},{e:.2f})" for s, e in spans)
            punched = os.path.join(P, "work", "punched.mp4")
            run(["ffmpeg", "-y", "-v", "error", "-i", joined, "-vf",
                 f"scale=w='trunc(iw*if({cond},{z},1)/2)*2':h='trunc(ih*if({cond},{z},1)/2)*2':eval=frame,crop={W}:{H},setsar=1",
                 "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-pix_fmt", "yuv420p", "-c:a", "copy", punched])
            joined = punched
    overlays = edl.get("overlays") or []
    if overlays:  # B-roll: [{"src": "intake/broll/x.mp4"|photo, "at": reel s, "dur": s, "from": src s (video)}]; main audio stays
        ins, fc, prev = ["-i", joined], [], "[0:v]"
        for k, o in enumerate(overlays, 1):
            src = os.path.join(P, o["src"])
            if src.lower().endswith((".jpg", ".jpeg", ".png", ".webp")):
                ins += ["-loop", "1", "-t", str(o["dur"]), "-i", src]
                zoom = f",zoompan=z='min(zoom+0.0008,1.08)':d=1:s={W}x{H}:fps={FPS}"  # slow push-in on photos
            else:
                ins += ["-ss", str(o.get("from", 0)), "-t", str(o["dur"]), "-i", src]
                zoom = ""
            fc.append(f"[{k}:v]scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H}{zoom},fps={FPS},setsar=1,"
                      f"setpts=PTS-STARTPTS+{o['at']}/TB[b{k}]")
            fc.append(f"{prev}[b{k}]overlay=enable='between(t,{o['at']},{o['at'] + o['dur']})':eof_action=pass[o{k}]")
            prev = f"[o{k}]"
        brolled = os.path.join(P, "work", "broll.mp4")
        run(["ffmpeg", "-y", "-v", "error", *ins, "-filter_complex", ";".join(fc), "-map", prev, "-map", "0:a",
             "-c:v", "libx264", "-preset", "veryfast", "-crf", "16", "-pix_fmt", "yuv420p", "-c:a", "copy", brolled])
        joined = brolled
    words_json = os.path.join(P, "work", "reel_words.json")
    json.dump(dict(duration=round(offset, 3), words=all_words), open(words_json, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    out = os.path.join(P, ex.get("out", "out/reel.mp4"))
    if a.lang == "en":
        all_words = en_words(P)
        words_json = os.path.join(P, "work", "reel_words_en.json")
        json.dump(dict(duration=round(offset, 3), words=all_words), open(words_json, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        out = os.path.splitext(out)[0] + "-en.mp4"
    cap = edl.get("captions") or {}
    sys.path.insert(0, STT)
    run([STT_PY, "-X", "utf8", "-c", "import sys,json; sys.path.insert(0,r'%s'); import sl_stt; d=json.load(open(r'%s',encoding='utf-8')); sl_stt.write_srt(d['words'], r'%s')"
         % (STT, words_json, os.path.splitext(out)[0] + ".srt")])
    if cap.get("style") in (None, "none"):
        shutil.copy2(joined, out)
    else:
        cmd = [sys.executable, "-X", "utf8", os.path.join(HERE, "captions", "render_captions.py"), words_json, out,
               "--style", cap["style"], "--bg", joined, "--audio", joined, "--top", str(cap.get("top", 1180))]
        if cap.get("accent"): cmd += ["--accent", cap["accent"]]
        if a.draft: cmd += ["--quality", "draft"]
        run(cmd)
    if all_words:  # cover candidate: the frame half a second into the hook, check it in the 4:5 grid crop
        run(["ffmpeg", "-y", "-v", "error", "-ss", f"{all_words[0]['s'] + 0.5:.2f}", "-i", out, "-frames:v", "1", "-q:v", "2", os.path.splitext(out)[0] + "-cover.jpg"])
    sheet = os.path.splitext(out)[0] + "-frames.png"
    run(["ffmpeg", "-y", "-v", "error", "-i", out, "-vf", f"fps=1/{max(1, int(offset // 8))},scale=270:480,tile=4x2", "-frames:v", "1", sheet])
    print(f"reel: {offset:.1f} s -> {out}  (contact sheet {sheet})")


def chunk(words, maxc=32, gap=0.35):
    out, cur = [], []
    for w in words:
        if cur and (len(" ".join(x["w"] for x in cur + [w])) > maxc or w["s"] - cur[-1]["e"] > gap):
            out.append(cur); cur = []
        cur.append(w)
        if w["w"][-1:] in ".!?": out.append(cur); cur = []
    if cur: out.append(cur)
    return out


def translate(a):
    """write work/en_chunks.json: timed Slovene caption chunks with an empty "en" field for the director to fill"""
    P = os.path.abspath(a.project)
    words = json.load(open(os.path.join(P, "work", "reel_words.json"), encoding="utf-8"))["words"]
    path = os.path.join(P, "work", "en_chunks.json")
    chunks = [dict(s=c[0]["s"], e=c[-1]["e"], sl=" ".join(x["w"] for x in c), en="") for c in chunk(words)]
    json.dump(dict(note="Fill every 'en' (same meaning, similar length, natural spoken English). Then: reel.py render PROJECT --lang en",
                   chunks=chunks), open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"{len(chunks)} chunks -> {path}")


def en_words(P):
    """English chunks -> pseudo word timings: each chunk's time spread over its words by length"""
    d = json.load(open(os.path.join(P, "work", "en_chunks.json"), encoding="utf-8"))
    missing = [c["sl"] for c in d["chunks"] if not c["en"].strip()]
    if missing: sys.exit(f"{len(missing)} chunks have no English yet, e.g. {missing[0]!r}")
    out = []
    for c in d["chunks"]:
        parts = c["en"].split(); total = sum(len(p) + 1 for p in parts); t = c["s"]
        for p in parts:
            dt = (c["e"] - c["s"]) * (len(p) + 1) / total
            out.append(dict(w=p, s=round(t, 3), e=round(t + dt, 3))); t += dt
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("ingest"); i.add_argument("project"); i.add_argument("clips", nargs="+")
    r = sub.add_parser("render"); r.add_argument("project"); r.add_argument("--draft", action="store_true")
    r.add_argument("--lang", default="sl", help="en: captions from work/en_chunks.json (run translate first), output gets -en")
    t = sub.add_parser("translate"); t.add_argument("project")
    a = ap.parse_args()
    {"ingest": ingest, "render": render, "translate": translate}[a.cmd](a)


if __name__ == "__main__":
    main()
